/**
 * Generates responsive AVIF / WebP / JPEG variants of every source image in
 * media-src/ and writes a typed manifest to src/content/media.generated.ts.
 *
 * Usage: npm run optimize:media
 * Add a new photo: drop a .jpg/.png in media-src/photos and run the script.
 */
import sharp from "sharp";
import { readdir, mkdir, writeFile, stat } from "node:fs/promises";
import path from "node:path";

const ROOT = path.resolve(import.meta.dirname, "..");
const OUT = path.join(ROOT, "public", "media");

const groups = [
  { dir: "photos", widths: [480, 828, 1280, 1920], quality: { avif: 44, webp: 68, jpeg: 72 } },
  { dir: "itineraries", widths: [640, 1024, 1536], quality: { avif: 60, webp: 80, jpeg: 80 } },
];

const manifest = {};

for (const group of groups) {
  const srcDir = path.join(ROOT, "media-src", group.dir);
  const outDir = path.join(OUT, group.dir);
  await mkdir(outDir, { recursive: true });
  for (const file of (await readdir(srcDir)).sort()) {
    if (!/\.(jpe?g|png)$/i.test(file)) continue;
    const name = file.replace(/\.(jpe?g|png)$/i, "");
    const input = sharp(path.join(srcDir, file));
    const meta = await input.metadata();
    const widths = group.widths.filter((w) => w <= meta.width);
    if (!widths.includes(meta.width) && widths.length < group.widths.length) widths.push(meta.width);
    const variants = [];
    for (const w of widths) {
      const base = path.join(outDir, `${name}-${w}`);
      const pipeline = sharp(path.join(srcDir, file)).resize({ width: w, withoutEnlargement: true });
      await pipeline.clone().avif({ quality: group.quality.avif, effort: 4 }).toFile(`${base}.avif`);
      await pipeline.clone().webp({ quality: group.quality.webp }).toFile(`${base}.webp`);
      await pipeline.clone().flatten({ background: "#141110" }).jpeg({ quality: group.quality.jpeg, mozjpeg: true, progressive: true }).toFile(`${base}.jpg`);
      variants.push(w);
    }
    // Tiny blurred placeholder (inline base64) for instant paint.
    const blur = await sharp(path.join(srcDir, file)).resize(24).blur(1.2).webp({ quality: 40 }).toBuffer();
    manifest[`${group.dir}/${name}`] = {
      src: `/media/${group.dir}/${name}`,
      width: meta.width,
      height: meta.height,
      widths: variants.sort((a, b) => a - b),
      blur: `data:image/webp;base64,${blur.toString("base64")}`,
    };
    console.log(`✓ ${group.dir}/${name} → ${variants.join(", ")}`);
  }
}

// Brand assets
await mkdir(path.join(OUT, "brand"), { recursive: true });
const logo = path.join(ROOT, "media-src/brand/logo.png");
for (const w of [160, 240, 320, 640]) {
  await sharp(logo).resize({ width: w }).webp({ quality: 72, effort: 6 }).toFile(path.join(OUT, "brand", `logo-${w}.webp`));
  await sharp(logo).resize({ width: w }).png({ compressionLevel: 9, palette: true }).toFile(path.join(OUT, "brand", `logo-${w}.png`));
}
const logoMeta = await sharp(logo).metadata();
const sto = path.join(ROOT, "media-src/brand/sto-garant.png");
for (const w of [96, 192]) {
  await sharp(sto).resize({ width: w }).webp({ quality: 90 }).toFile(path.join(OUT, "brand", `sto-garant-${w}.webp`));
  await sharp(sto).resize({ width: w }).png({ compressionLevel: 9 }).toFile(path.join(OUT, "brand", `sto-garant-${w}.png`));
}
const stoMeta = await sharp(sto).metadata();

// Open Graph image (1200x630)
await sharp(path.join(ROOT, "media-src/photos/hero-road.jpg"))
  .resize(1200, 630, { fit: "cover", position: "centre" })
  .composite([{ input: await sharp(logo).resize({ width: 300 }).toBuffer(), gravity: "southwest", top: 300, left: 60 }])
  .jpeg({ quality: 82, mozjpeg: true })
  .toFile(path.join(ROOT, "public", "og-image.jpg"));

const ts = `// AUTO-GENERATED by scripts/optimize-images.mjs. Do not edit by hand.
export const media = ${JSON.stringify(manifest, null, 2)} as const;

export type MediaKey = keyof typeof media;

export const brand = {
  logo: { src: "/media/brand/logo", width: ${logoMeta.width}, height: ${logoMeta.height} },
  sto: { src: "/media/brand/sto-garant", width: ${stoMeta.width}, height: ${stoMeta.height} },
} as const;
`;
await mkdir(path.join(ROOT, "src/content"), { recursive: true });
await writeFile(path.join(ROOT, "src/content/media.generated.ts"), ts);
const s = await stat(path.join(ROOT, "public/og-image.jpg"));
console.log(`✓ manifest written, og-image ${Math.round(s.size / 1024)} KB`);
